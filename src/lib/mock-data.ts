export function formatPrice(price: number, currency: string, type: string) {
  const f = new Intl.NumberFormat("fr-FR").format(price);
  const suffix = type === "rent" ? " /mois" : type === "vacation" ? " /nuit" : "";
  return `${f} ${currency}${suffix}`;
}

